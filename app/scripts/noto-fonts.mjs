// Builds src/lib/fonts/noto.css from the @fontsource-variable Noto packages.
// Run after changing or updating those packages: node scripts/noto-fonts.mjs
//
// - Base Noto Sans keeps every subset (Latin extras, Cyrillic, Greek...).
// - The script families keep only their own script. Their Latin and Cyrillic
//   copies are never drawn (Bricolage and Noto Sans come first) and would
//   only make the installer bigger.
// - Chinese, Japanese and Korean (18 MB) aren't bundled: they load from
//   jsDelivr, pinned to the installed version, one small range at a time and
//   only when text in them is on screen.
import { readFileSync, writeFileSync } from "node:fs";

const LOCAL = [
  "noto-sans", "noto-sans-bengali", "noto-sans-devanagari", "noto-sans-arabic", "noto-sans-hebrew", "noto-sans-thai",
  "noto-sans-tamil", "noto-sans-telugu", "noto-sans-kannada", "noto-sans-malayalam", "noto-sans-gujarati",
  "noto-sans-gurmukhi", "noto-sans-sinhala", "noto-sans-myanmar", "noto-sans-khmer", "noto-sans-lao",
  "noto-sans-georgian", "noto-sans-armenian", "noto-sans-ethiopic", "noto-sans-oriya",
];
const REMOTE = ["noto-sans-jp", "noto-sans-kr", "noto-sans-sc", "noto-sans-tc"];
const SHARED = /-(latin|latin-ext|vietnamese|cyrillic|cyrillic-ext|greek|greek-ext)-wght-normal$/;

const pkg = (f) => `node_modules/@fontsource-variable/${f}`;
let out = "/* Generated by scripts/noto-fonts.mjs. Don't edit by hand. */\n";
let kept = 0;

for (const f of [...LOCAL, ...REMOTE]) {
  const css = readFileSync(`${pkg(f)}/wght.css`, "utf8");
  const version = JSON.parse(readFileSync(`${pkg(f)}/package.json`, "utf8")).version;
  const blocks = css.split(/(?=\/\* )/).filter((b) => b.includes("@font-face"));
  for (const block of blocks) {
    const name = block.match(/\/\* ([^ ]+) \*\//)?.[1] ?? "";
    if (f !== "noto-sans" && SHARED.test(name)) continue;
    const base = REMOTE.includes(f)
      ? `https://cdn.jsdelivr.net/npm/@fontsource-variable/${f}@${version}/files/`
      : `../../../node_modules/@fontsource-variable/${f}/files/`;
    out += block.replace(/url\(\.\/files\//g, `url(${base}`).trimEnd() + "\n\n";
    kept++;
  }
}

writeFileSync("src/lib/fonts/noto.css", out);
console.log(`noto.css: ${kept} faces`);
